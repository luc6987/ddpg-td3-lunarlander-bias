"""Table 1 (hyper-parameters), Table 2 (results) and the run table.

`docs/implementation_plan.md` §12:

- `table1_hparams.tex` is built from the `config.json` of the E1 runs, and it
  asserts that every field that is not one of E1's factors is identical across
  the block;
- `table2_results.tex` gives $P$ and $B$ per condition as mean [95 % CI] and
  median, and the Family A/B contrasts with Δ [CI], Welch p, Holm p, Hedges g
  and the Mann–Whitney p;
- `run_table.csv` lists every run with its state and wall time, so nothing that
  crashed or diverged can silently disappear.
"""

from __future__ import annotations

import dataclasses
import json
from pathlib import Path
from typing import Any

import pandas as pd

from lunar_bias.analysis.load import RunData
from lunar_bias.envs import ENV_ID

#: Fields E1 is allowed to vary; everything else must be constant across the block.
E1_VARIED = ("algo.name", "critic.norm", "seed")


def flat_config(cfg: Any) -> dict[str, Any]:
    """A `RunConfig` as flat `section.field` scalars (lists become tuples of ints)."""
    out: dict[str, Any] = {}
    for section in dataclasses.fields(cfg):
        value = getattr(cfg, section.name)
        if section.name == "tag":  # not scientific, and not part of run_id
            continue
        if dataclasses.is_dataclass(value):
            for field in dataclasses.fields(value):
                item = getattr(value, field.name)
                out[f"{section.name}.{field.name}"] = tuple(item) \
                    if isinstance(item, (list, tuple)) else item
        else:
            out[section.name] = tuple(value) if isinstance(value, (list, tuple)) else value
    return out


def table1_hparams(runs: list[RunData]) -> tuple[str, str]:
    """LaTeX and CSV of the E1 hyper-parameters; raises if a hidden field varies."""
    if not runs:
        raise RuntimeError("table1 needs at least one E1 run")
    configs = [flat_config(run.cfg) for run in runs]
    keys = list(configs[0])
    varied = {key for key in keys if len({json.dumps(c[key]) for c in configs}) > 1}
    unexpected = varied - set(E1_VARIED)
    if unexpected:
        raise RuntimeError("E1 must vary only algo.name, critic.norm and seed; "
                           f"these fields vary too: {sorted(unexpected)}")
    reference = configs[0]
    seeds = sorted(c["seed"] for c in configs)
    seen = set()
    algo_norm = sorted({(c["algo.name"], c["critic.norm"]) for c in configs})
    for key in keys:
        seen.add(key)

    rows: list[tuple[str, str]] = [
        ("Environment", f"{ENV_ID}, continuous actions, no wind"),
        ("Training steps", f"{reference['max_steps']:,} (one environment)"),
        ("Evaluation", f"every {reference['evaluation.every']:,} steps, "
                       f"{len(reference['evaluation.seeds'])} fixed seeds "
                       f"({reference['evaluation.seeds'][0]:,}–"
                       f"{reference['evaluation.seeds'][-1]:,})"),
        ("Probe horizon", f"{reference['evaluation.probe_horizon']:,} steps "
                          f"(performance uses the first "
                          f"{reference['evaluation.train_horizon']:,})"),
        # "Checkpoint" in the report means an evaluation step (every 10 k).
        ("Saved weights", f"every {reference['evaluation.checkpoint_every']:,} steps "
                          "and at the end"),
        ("Warm-up", f"{reference['algo.learning_starts']:,} uniform random actions, "
                    "no gradient update before"),
        ("Exploration noise", f"Gaussian, σ = {reference['algo.action_noise']}"),
        ("Actor / critic nets", f"{reference['actor.hidden']} ReLU, tanh output"
                                " (fallback after the pilot gate)"),
        ("Critic normalisation", "none or LayerNorm after each hidden Linear, "
                                 "before the ReLU (never on the output, never "
                                 "in the actor)"),
        ("Batch / buffer", f"{reference['algo.batch_size']} / "
                           f"{reference['algo.buffer_size']:,} (never full)"),
        ("Discount γ / Polyak τ", f"{reference['algo.gamma']} / {reference['algo.tau']}"),
        ("Optimiser", f"Adam, lr {reference['algo.lr_actor']} (actor and critic)"),
        ("Target networks", "both algorithms: target actor and target critic(s)"),
        ("TD3 only", f"policy delay {reference['algo.policy_delay']}, target noise "
                     f"{reference['algo.target_noise']} clipped at "
                     f"{reference['algo.target_noise_clip']}, reduction min"),
        ("UTD", f"{reference['algo.utd']} gradient step per environment step"),
        ("E1 factors", "; ".join(f"{algo}/{norm}" for algo, norm in algo_norm)),
        ("Seeds", f"{seeds[0]}–{seeds[-1]}" if seeds else "-"),
    ]
    tex = ["% Generated by scripts/analyze.py from runs/*/config.json — do not edit.",
           "\\begin{tabular}{@{}ll@{}}", "\\hline",
           "Setting & Value \\\\", "\\hline"]
    tex += [f"{name} & {value} \\\\" for name, value in rows]
    tex += ["\\hline", "\\end{tabular}", ""]
    csv = ["setting,value"] + [f'"{name}","{value}"' for name, value in rows]
    return "\n".join(tex), "\n".join(csv) + "\n"


def table2_results(descriptives: dict[str, dict[str, Any]],
                   contrasts: dict[str, dict[str, Any]],
                   page: dict[str, dict[str, Any]] | None = None
                   ) -> tuple[str, str]:
    """LaTeX and CSV of the per-condition summaries and the pre-registered tests.

    `descriptives` maps a condition label to `{"P": describe(...), "B": ...}`;
    `contrasts` maps e.g. `"Family A: H1"` to a Welch result with `p_holm`;
    `page` maps `"C0"`/`"C1"` to a Page result.
    """
    tex = ["% Generated by scripts/analyze.py — do not edit.",
           "\\begin{tabular}{@{}lrrrrr@{}}", "\\hline",
           "Condition & n & $P$ mean [95 \\% CI] & $P$ median & "
           "$B$ mean [95 \\% CI] & $B$ median \\\\", "\\hline"]
    for label, stats in descriptives.items():
        p, b = stats["P"], stats["B"]
        tex.append(f"{label} & {p['n']} & {_mean_ci(p)} & {_num(p['median'])} & "
                   f"{_mean_ci(b)} & {_num(b['median'])} \\\\")
    tex += ["\\hline", "\\end{tabular}", "", "\\medskip", "",
            "\\begin{tabular}{@{}lrrrrr@{}}", "\\hline",
            "Contrast & $\\Delta$ [95 \\% CI] & Welch $p$ & Holm $p$ & Hedges $g$ & "
            "Mann--Whitney $p$ \\\\", "\\hline"]
    for label, r in contrasts.items():
        tex.append(f"{label} & {_delta_ci(r)} & {_p(r['p'])} & {_p(r['p_holm'])} & "
                   f"{r['hedges_g']:.2f} & {_p(r['mw_p'])} \\\\")
    tex += ["\\hline", "\\end{tabular}", ""]
    if page:
        tex += ["\\medskip", "", "\\begin{tabular}{@{}lrrll@{}}", "\\hline",
                "Page trend test & $L$ & $p$ & blocks & method \\\\", "\\hline"]
        for label, r in page.items():
            tex.append(f"{label} & {r['L']:.1f} & {_p(r['p'])} & {r['n_blocks']} & "
                       f"{r['method']} \\\\")
        tex += ["\\hline", "\\end{tabular}", ""]

    rows = []
    for label, stats in descriptives.items():
        for metric in ("P", "B", "B_mid"):
            s = stats.get(metric)
            if s is None:
                continue
            rows.append({"block": "descriptive", "name": label, "metric": metric,
                         "n": s["n"], "mean": s["mean"], "ci_lo": s["ci_lo"],
                         "ci_hi": s["ci_hi"], "median": s["median"], "sd": s["sd"],
                         "delta": "", "delta_ci_lo": "", "delta_ci_hi": "",
                         "p_welch": "", "p_holm": "", "hedges_g": "", "p_mannwhitney": ""})
    for label, r in contrasts.items():
        rows.append({"block": "contrast", "name": label, "metric": r.get("metric", "P"),
                     "n": f"{r['n_x']} vs {r['n_y']}", "mean": "", "ci_lo": "", "ci_hi": "",
                     "median": "", "sd": "", "delta": r["delta"], "delta_ci_lo": r["ci_lo"],
                     "delta_ci_hi": r["ci_hi"], "p_welch": r["p"], "p_holm": r["p_holm"],
                     "hedges_g": r["hedges_g"], "p_mannwhitney": r["mw_p"]})
    for label, r in (page or {}).items():
        rows.append({"block": "page", "name": label, "metric": label,
                     "n": r["n_blocks"], "mean": "", "ci_lo": "", "ci_hi": "",
                     "median": "", "sd": "", "delta": r["L"], "delta_ci_lo": "",
                     "delta_ci_hi": "", "p_welch": r["p"], "p_holm": "",
                     "hedges_g": "", "p_mannwhitney": ""})
    csv = pd.DataFrame(rows).to_csv(index=False)
    return "\n".join(tex), csv


def run_table(index: pd.DataFrame) -> pd.DataFrame:
    """Every run directory with its condition, state and wall time."""
    columns = ["run_id", "state", "algo", "critic_norm", "reduction", "utd", "depth",
               "width", "seed", "max_steps", "step", "wall_s", "grids"]
    return index[columns].copy()


def _num(value: float) -> str:
    return "n/a" if value is None or pd.isna(value) else f"{value:.1f}"


def _mean_ci(stats: dict[str, Any]) -> str:
    return f"{stats['mean']:.1f} [{stats['ci_lo']:.1f}, {stats['ci_hi']:.1f}]"


def _delta_ci(r: dict[str, Any]) -> str:
    return f"{r['delta']:.1f} [{r['ci_lo']:.1f}, {r['ci_hi']:.1f}]"


def _p(value: float) -> str:
    return f"{value:.4f}" if value >= 1e-4 else f"{value:.1e}"


def write(out_dir: Path, name: str, tex: str, csv: str) -> list[Path]:
    """Write `<name>.tex` and `<name>.csv` under `out_dir`; return both paths."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    tex_path = out_dir / f"{name}.tex"
    csv_path = out_dir / f"{name}.csv"
    tex_path.write_text(tex)
    csv_path.write_text(csv)
    return [tex_path, csv_path]
